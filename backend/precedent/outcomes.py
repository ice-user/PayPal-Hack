"""Outcome Tracker with a SIMULATED clock.

After approved actions run, the merchant presses "advance time". We replay the same
synthetic merchant for the next 14 days with the planted cause reduced if the chosen
fix addresses it, rebuild the situation, and record before/after. The result is
stored as an outcome (simulated=True) and as a live_simulated case pending review.

Nothing here is a real-world measurement, and the case it creates is labelled
`simulated`, so it can never drive a numeric forecast.
"""
from __future__ import annotations

from dataclasses import replace
from datetime import timedelta

from .orders import Scenario, generate
from .situation_builder import build

# How much of the planted extra dispute rate remains after a fix, by (cause, chosen family).
# Illustrative simulation parameters, not estimates of real effects.
RESIDUAL = {"match": 0.35, "partial": 0.75, "none": 1.0}
SCENARIO_FAMILY = {"carrier": "carrier", "fulfilment": "fulfilment", "delivered": "delivered",
                   "fraud": "fraud", "snad": "listing"}


def simulate(scenario: Scenario, chosen_family: str | None, *, horizon_days: int = 14) -> dict:
    cause = SCENARIO_FAMILY.get(scenario.kind)
    fit = "match" if chosen_family and chosen_family == cause else ("none" if not chosen_family else "partial")
    after_s = replace(scenario, seed=scenario.seed + 1000, end=scenario.end + timedelta(days=horizon_days),
                      extra_rate=scenario.extra_rate * RESIDUAL[fit])
    after = build(generate(after_s), situation_id="sit_sim_after")["features"]
    return {"fit": fit, "after_rate": after["dispute_rate_7d"], "after_features": after, "horizon_days": horizon_days}


def live_simulated_case(rec: dict, situation: dict, before: float, after: float, horizon: int, n: int) -> dict:
    f = situation["features"]
    return {
        "case_id": f"case_ls_{rec['recommendation_id'].removeprefix('rec_').lower()}_{n}",
        "title": f"Sandbox replay: {rec['diagnosis']}",
        "provenance": "live_simulated", "evidence_quality": "simulated", "causal_claim": False,
        "confounders_assessed": False, "review_status": "pending",
        "source": {"ref": f"Generated by the Precedent outcome tracker from {rec['recommendation_id']} (simulated clock)."},
        "context": {"industry": "consumer electronics", "merchant_size": "mid", "region": "US", "channel": "web store"},
        "situation_features": {
            "dispute_rate_before": f["dispute_rate_7d"],
            "inr_share": f["reason_mix"].get("ITEM_NOT_RECEIVED", 0.0),
            "unauthorised_share": f["reason_mix"].get("UNAUTHORISED", 0.0),
            "snad_share": f["reason_mix"].get("NOT_AS_DESCRIBED", 0.0),
            "concentration_carrier": f["concentration"].get("carrier", 0.0),
            "concentration_sku": f["concentration"].get("sku", 0.0),
            "carriers_elevated": f["carriers_elevated"],
            "ship_delay_hours_p50": f["ship_delay_hours_p50"],
            "disputed_orders_delivered_share": f["disputed_orders_delivered_share"],
        },
        "narrative": situation["narrative"],
        "diagnosis": rec["diagnosis"],
        "intervention": rec["precedents"][0]["intervention"] if rec["precedents"] else "fraud_screening",
        "actions": sorted({a["type"] for a in rec["actions"]}) or ["FLAG_ONLY"],
        "outcome": {"summary": (f"Simulated: 7-day dispute rate {before * 100:.2f}% before, {after * 100:.2f}% after "
                                f"{horizon} simulated days. Not a real-world measurement."),
                    "metric": "dispute_rate_7d", "before": None, "after": None, "observed_change": None,
                    "measurement_period_days": None},
        "tags": ["live_simulated", "pending_review"],
    }
